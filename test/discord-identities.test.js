test('name request DMs go to the owner, retry transient errors, and remain reviewable if DMs are blocked',async t=>{
  const s=fixture(t);let time=new Date('2026-09-04T12:00:00Z');s.now=()=>time;s.importGame(named('SharedAlt'));
  const r=s.requestNameChange(USER,'G1','SharedAlt','Sputtered','Used this alt');
  const sent=[];const notifier=new NameRequestNotifier({store:s,log:()=>{},send:async(user,payload)=>{sent.push({user,payload});throw new Error('Temporary error');}});
  await notifier.tick();assert.equal(sent[0].user,ADMIN_ID);assert.equal(s.nameRequest(r.id).dm_status,'pending');
  assert.match(sent[0].payload.components[0].components[0].custom_id,new RegExp(`rp:${ADMIN_ID}:approvename`));
  await notifier.tick();assert.equal(sent.length,1);
  time=new Date(time.getTime()+31_000);await notifier.tick();assert.equal(sent.length,2);
  assert.equal(sent[0].payload.nonce,sent[1].payload.nonce);
  time=new Date(time.getTime()+61_000);
  notifier.send=async()=>{throw Object.assign(new Error('Closed DMs'),{code:50007});};await notifier.tick();
  assert.equal(s.nameRequest(r.id).dm_status,'failed');assert.equal(s.nameRequest(r.id).status,'pending');
  s.reviewNameRequest(ADMIN_ID,r.id,true);assert.equal(playerStats(s.games(),'Sputtered').games,1);await notifier.stop();
});
