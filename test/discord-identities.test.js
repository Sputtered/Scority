function named(name, options={}) {
  const payload=game(options);
  payload.teams={red:['Sputtered'],green:['Mikowa'],unassigned:[]};
  payload.headToHead={Sputtered:{Mikowa:{kills:payload.players.Sputtered.kills,deaths:payload.players.Sputtered.deaths}},Mikowa:{Sputtered:{kills:1,deaths:2}}};
  payload.awards={mostKills:'Sputtered',bestKD:'Sputtered',firstBlood:'Sputtered',longestStreak:{player:'Sputtered',length:2},noDeaths:['Sputtered']};
  const result=JSON.parse(JSON.stringify(payload).replaceAll('Sputtered',name));
  result.killFeed[0].raw=`${name} killed Mikowa`;
  return result;
}
test('nick and dedicated-alt links update historical and future results with every structured name',t=>{
  const s=fixture(t); const raw=named('HiddenNick'); const id=s.importGame(raw);
  s.importGame(named('PrivateAlt',{index:2}));
  s.importGame(named('Sputtered',{index:3}));
  s.addNameLink(ADMIN_ID,'HiddenNick','Sputtered','nick');
  s.addNameLink(ADMIN_ID,'PrivateAlt','Sputtered','alt');
  s.importGame(named('HiddenNick',{index:4,winner:'green'}));
  const p=matchup(s.games(),'Sputtered','Mikowa');
  assert.equal(p.wins,3);assert.equal(p.losses,1);assert.equal(p.kills,8);assert.equal(p.deaths,4);
  assert.equal(playerStats(s.games(),'Sputtered').games,4);
  assert.equal(playerGames(s.games(),'Sputtered').length,4);
  assert.equal(rivals(s.games(),'Sputtered')[0].games,4);
  assert.equal(leaderboard(s.games(),'kd').length,2);
  assert.equal(s.resolvePlayer('hIDDENnICK'),'Sputtered');
  const scored=s.getGame(id).payload;
  assert.deepEqual(scored.players.Sputtered,raw.players.HiddenNick);
  assert.equal(scored.players.HiddenNick,undefined);
  assert.equal(scored.killFeed[0].killer,'Sputtered');assert.equal(scored.killFeed.at(-1).victim,'Sputtered');
  assert.equal(scored.bedBreaks[0].breaker,'Sputtered');assert.deepEqual(scored.teams.red,['Sputtered']);
  assert.equal(scored.headToHead.Sputtered.Mikowa.kills,2);assert.equal(scored.headToHead.Mikowa.Sputtered.kills,1);
  assert.equal(scored.awards.firstBlood,'Sputtered');assert.equal(scored.awards.mostKills,'Sputtered');
  assert.equal(scored.awards.bestKD,'Sputtered');assert.equal(scored.awards.longestStreak.player,'Sputtered');
  assert.deepEqual(scored.awards.noDeaths,['Sputtered']);
  assert.equal(scored.killFeed[0].raw,'HiddenNick killed Mikowa');
  assert.deepEqual(JSON.parse(s.db.prepare('SELECT payload FROM games WHERE id=?').get(id).payload),raw);
  assert.equal(s.importGame(raw),id);assert.equal(s.games().length,4);
});
